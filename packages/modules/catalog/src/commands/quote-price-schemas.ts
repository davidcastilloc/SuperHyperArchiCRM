import { z } from 'zod';

export const quotePriceInputSchema = z.object({
  productId: z.string().min(1),
  variantId: z.string().min(1).optional(),
  qty: z.number().int().positive().default(1),
  partyId: z.string().min(1).optional(),
  groupIds: z.array(z.string().min(1)).optional(),
  priceListId: z.string().min(1).optional(),
  tariffKind: z.string().min(1).optional(),
  channelId: z.string().min(1).optional(),
  secondaryCurrency: z.string().trim().min(3).max(8).optional(),
  allowBelowCost: z.boolean().optional(),
  minMarginBps: z.number().int().min(0).max(10_000).default(0),
  asOfSec: z.number().int().positive().optional(),
});

export const quotePriceOutputSchema = z.object({
  productId: z.string(),
  variantId: z.string().nullable(),
  unitPriceMinor: z.number().int(),
  unitCostMinor: z.number().int(),
  baseReferencePriceMinor: z.number().int(),
  appliedLayer: z.enum([
    'CONTRACT_1TO1',
    'GROUP_TARIFF',
    'PROMOTION_CHANNEL',
    'VARIANT_UOM',
    'BASE_PRICE',
  ]),
  appliedRuleId: z.string().nullable(),
  appliedPriceListId: z.string().nullable(),
  marginBps: z.number().int(),
  taxRateBps: z.number().int(),
  unitTaxMinor: z.number().int(),
  unitPriceWithTaxMinor: z.number().int(),
  qty: z.number().int().positive(),
  lineSubtotalMinor: z.number().int(),
  lineTaxMinor: z.number().int(),
  lineTotalMinor: z.number().int(),
  primaryCurrency: z.string(),
  secondaryCurrency: z.string().nullable(),
  rateMicros: z.number().int().nullable(),
  secondaryUnitPriceMinor: z.number().int().nullable(),
  secondaryUnitPriceWithTaxMinor: z.number().int().nullable(),
  secondaryLineTotalMinor: z.number().int().nullable(),
  lowest30dMinor: z.number().int().nullable(),
  isBelow30dLowest: z.boolean(),
});
