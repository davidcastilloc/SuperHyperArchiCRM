import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const catCategoriesAndDictionaries = sqliteTable(
  'cat_categories_and_dictionaries',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    kind: text('kind').notNull().default('product_category'),
    parentId: text('parent_id'),
    treePath: text('tree_path').notNull().default('/'),
    code: text('code').notNull(),
    name: text('name').notNull(),
    color: text('color'),
    icon: text('icon'),
    sortOrder: integer('sort_order').notNull().default(0),
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    uniqueIndex('cat_categories_tenant_kind_code_uniq').on(t.tenantId, t.kind, t.code),
    index('cat_categories_tenant_org_path_idx').on(t.tenantId, t.orgId, t.treePath),
  ],
);

