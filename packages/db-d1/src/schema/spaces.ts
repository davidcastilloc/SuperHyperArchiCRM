import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const spcUnitTypes = sqliteTable(
  'spc_unit_types',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    code: text('code').notNull(),
    name: text('name').notNull(),
    spaceCategory: text('space_category').notNull().default('hotel_room'),
    maxOccupancy: integer('max_occupancy').notNull().default(1),
    bedOrLayoutType: text('bed_or_layout_type'),
    areaSqft: integer('area_sqft'),
    baseRateMinor: integer('base_rate_minor').notNull().default(0),
    ratePeriod: text('rate_period').notNull().default('night'),
    amenitiesJson: text('amenities_json').notNull().default('[]'),
    mediaUrlsJson: text('media_urls_json').notNull().default('[]'),
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    uniqueIndex('spc_unit_types_tenant_code_uniq').on(t.tenantId, t.code),
    index('spc_unit_types_tenant_org_cat_idx').on(t.tenantId, t.orgId, t.spaceCategory),
  ],
);

