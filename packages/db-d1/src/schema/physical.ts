import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const phyDevicesAndLocks = sqliteTable(
  'phy_devices_and_locks',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    unitId: text('unit_id'),
    deviceCode: text('device_code').notNull(),
    name: text('name').notNull(),
    deviceKind: text('device_kind').notNull().default('SMART_DOOR_LOCK'),
    vendorDriver: text('vendor_driver').notNull().default('smartlock_cloud'),
    linkedCameraId: text('linked_camera_id'),
    batteryPct: integer('battery_pct'),
    lockState: text('lock_state').notNull().default('LOCKED'),
    autoLockSec: integer('auto_lock_sec').notNull().default(10),
    dualPathMode: integer('dual_path_mode', { mode: 'boolean' }).notNull().default(false),
    lastHeartbeatAt: integer('last_heartbeat_at'),
    watchdogStatus: text('watchdog_status').notNull().default('ONLINE'),
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    uniqueIndex('phy_devices_tenant_code_uniq').on(t.tenantId, t.deviceCode),
    index('phy_devices_tenant_org_kind_idx').on(t.tenantId, t.orgId, t.deviceKind),
    index('phy_devices_tenant_unit_idx').on(t.tenantId, t.unitId),
  ],
);

