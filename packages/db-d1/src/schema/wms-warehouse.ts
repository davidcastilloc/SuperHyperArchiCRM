import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const wmsWarehousesAndZones = sqliteTable(
  'wms_warehouses_and_zones',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    code: text('code').notNull(),
    name: text('name').notNull(),
    zoneCode: text('zone_code'),
    zoneKind: text('zone_kind').notNull().default('dry'),
    tempMinC: integer('temp_min_c'),
    tempMaxC: integer('temp_max_c'),
    capacityVolumeCm3: integer('capacity_volume_cm3'),
    capacityWeightGrams: integer('capacity_weight_grams'),
    managerUserId: text('manager_user_id'),
    isPrimary: integer('is_primary', { mode: 'boolean' }).notNull().default(false),
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    index('wms_warehouses_tenant_org_code_idx').on(t.tenantId, t.orgId, t.code),
    index('wms_warehouses_tenant_code_idx').on(t.tenantId, t.code),
  ],
);

