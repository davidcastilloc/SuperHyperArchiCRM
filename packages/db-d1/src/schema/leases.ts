import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const leaseApplications = sqliteTable(
  'lease_applications',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    applicantPartyId: text('applicant_party_id').notNull(),
    targetUnitId: text('target_unit_id').notNull(),
    applicationKind: text('application_kind').notNull().default('NEW_LEASE'),
    desiredMoveIn: integer('desired_move_in').notNull(),
    termMonths: integer('term_months').notNull().default(12),
    proposedRentMinor: integer('proposed_rent_minor').notNull().default(0),
    screeningScore: integer('screening_score'),
    stepsTimelineJson: text('steps_timeline_json').notNull().default('[]'),
    coApplicantJson: text('co_applicant_json').notNull().default('{}'),
    petSummaryJson: text('pet_summary_json').notNull().default('{}'),
    signatureSvg: text('signature_svg'),
    status: text('status').notNull().default('SUBMITTED'),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    index('lease_apps_tenant_org_status_idx').on(t.tenantId, t.orgId, t.status),
    index('lease_apps_tenant_unit_idx').on(t.tenantId, t.targetUnitId),
    index('lease_apps_tenant_party_idx').on(t.tenantId, t.applicantPartyId),
  ],
);

export const leaseContractsAndRenewals = sqliteTable(
  'lease_contracts_and_renewals',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    recordKind: text('record_kind').notNull().default('active_lease'),
    leaseNumber: text('lease_number').notNull(),
    unitId: text('unit_id').notNull(),
    primaryPartyId: text('primary_party_id').notNull(),
    occupantsJson: text('occupants_json').notNull().default('[]'),
    startDate: integer('start_date').notNull(),
    endDate: integer('end_date').notNull(),
    monthlyRentMinor: integer('monthly_rent_minor').notNull().default(0),
    recurringBreakdownJson: text('recurring_breakdown_json').notNull().default('{}'),
    securityDepositEscrowMinor: integer('security_deposit_escrow_minor').notNull().default(0),
    gracePeriodDays: integer('grace_period_days').notNull().default(5),
    lateFeeMinor: integer('late_fee_minor').notNull().default(0),
    autopayEnabled: integer('autopay_enabled', { mode: 'boolean' }).notNull().default(false),
    autopayDayOfMonth: integer('autopay_day_of_month'),
    splitRentSharesJson: text('split_rent_shares_json').notNull().default('[]'),
    renewalIncentivesJson: text('renewal_incentives_json').notNull().default('{}'),
    vacateNoticeJson: text('vacate_notice_json').notNull().default('{}'),
    electronicSignatureSvg: text('electronic_signature_svg'),
    status: text('status').notNull().default('DRAFT'),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    uniqueIndex('lease_contracts_tenant_number_uniq').on(t.tenantId, t.leaseNumber),
    index('lease_contracts_tenant_org_status_idx').on(t.tenantId, t.orgId, t.status),
    index('lease_contracts_tenant_unit_idx').on(t.tenantId, t.unitId),
    index('lease_contracts_tenant_party_idx').on(t.tenantId, t.primaryPartyId),
  ],
);

export const condoCommunityHub = sqliteTable(
  'condo_community_hub',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    itemKind: text('item_kind').notNull().default('announcement'),
    partyId: text('party_id'),
    unitId: text('unit_id'),
    title: text('title').notNull(),
    bodyOrDetailsJson: text('body_or_details_json').notNull().default('{}'),
    priority: text('priority').notNull().default('NORMAL'),
    startsAt: integer('starts_at'),
    endsAt: integer('ends_at'),
    status: text('status').notNull().default('ACTIVE'),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    index('condo_hub_tenant_org_kind_idx').on(t.tenantId, t.orgId, t.itemKind),
    index('condo_hub_tenant_status_idx').on(t.tenantId, t.status),
  ],
);
