import {
  index,
  integer,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const posRegistersAndDisplays = sqliteTable(
  'pos_registers_and_displays',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    code: text('code').notNull(),
    name: text('name').notNull(),
    deviceMode: text('device_mode').notNull().default('POS_REGISTER'),
    defaultWarehouseId: text('default_warehouse_id'),
    printerConfigJson: text('printer_config_json').notNull().default('{}'),
    squareTerminalId: text('square_terminal_id'),
    fiscalPrinterSerial: text('fiscal_printer_serial'),
    isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [
    uniqueIndex('pos_registers_tenant_code_uniq').on(t.tenantId, t.code),
    index('pos_registers_tenant_org_mode_idx').on(t.tenantId, t.orgId, t.deviceMode),
  ],
);

