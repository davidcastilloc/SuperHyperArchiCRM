import { index, integer, sqliteTable, text } from 'drizzle-orm/sqlite-core';

export const crmPipelinesAndStages = sqliteTable(
  'crm_pipelines_and_stages',
  {
    id: text('id').primaryKey(),
    tenantId: text('tenant_id').notNull(),
    orgId: text('org_id').notNull(),
    pipelineName: text('pipeline_name').notNull(),
    isDefault: integer('is_default', { mode: 'boolean' }).notNull().default(false),
    stagesJson: text('stages_json').notNull().default('[]'),
    stuckThresholdDays: integer('stuck_threshold_days').notNull().default(14),
    customFields: text('custom_fields').notNull().default('{}'),
    version: integer('version').notNull().default(1),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull(),
    deletedAt: integer('deleted_at'),
  },
  (t) => [index('crm_pipelines_tenant_org_idx').on(t.tenantId, t.orgId)],
);

